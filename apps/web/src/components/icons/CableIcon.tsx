import type { SVGProps } from "react";

// Категорія CABLE. Той самий словник форм, що й у решти іконок цієї
// теки: 24x24, тільки обведення (stroke), товщина 1.75, круглі кінці —
// щоб у сітці категорій на головній вони читались як один набір, а не
// як зібрані з різних місць.
//
// Форма — бухта (котушка) кабелю з виведеним кінцем. Дві попередні
// спроби перевірені рендером і відкинуті саме на ньому:
//   • S-подібний вигин по діагоналі читався як «маршрут/шлях» і був
//     помітно легшим за сусідні іконки;
//   • дуга між двома наконечниками внизу давала силует навушників.
// Бухта, по-перше, ні на що не схожа в цьому наборі (жодна інша іконка
// не кругла), по-друге — чесна: кабель у цьому каталозі й продається
// метражем з бухти (Product.specs.crossSectionMm2, ціна за погонний
// метр), а не готовим шнуром із роз'ємами на кінцях.
export function CableIcon(props: SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {/* Бухта: зовнішній виток і внутрішній отвір */}
      <circle cx="10.4" cy="13.2" r="7" />
      <circle cx="10.4" cy="13.2" r="2.8" />
      {/* Проміжний виток — щоб кільце читалось як намотаний провід,
          а не як шайба */}
      <path d="M10.4 8.5a4.7 4.7 0 0 1 4.5 3.3" />
      {/* Виведений кінець: провід сходить із бухти й закінчується
          зачищеними жилами. Суцільний прямокутник-наконечник тут уже
          пробувався — на рендері вся іконка через нього починала
          читатись як ключ. Дві короткі жили такого ефекту не дають і
          заразом кажуть, що це саме кабель на відріз, без роз'ємів. */}
      <path d="M15.9 8.6c1.1-1.4 2.3-2.4 3.7-3" />
      <path d="M19.6 5.6 21.8 6.6M19.6 5.6l.6-2.3" />
    </svg>
  );
}
