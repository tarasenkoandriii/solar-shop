// Завантаження інтерпольованої сітки сонячного потенціалу для публічних
// сторінок. Один спільний файл, а не три однакові рядки в page.tsx —
// бо саме розбіжність між ними й ховала помилку: головна, /solar-map та
// /embed/solar-map робили той самий запит із тим самим 24-годинним
// revalidate, і коли в Data Cache застряг порожній масив, "зламались"
// одночасно всі три, але виглядало це як три різні дрібниці.
//
// ВАЖЛИВО: звідси НЕ можна імпортувати нічого, крім типу, з
// components/SolarPotentialMap.tsx — той файл 'use client'. Імпорт типу
// стирається на компіляції й безпечний; імпорт функції з клієнтського
// модуля в серверний дав би в проді `TypeError: d is not a function`
// (уже траплялось у цьому проєкті з lib/currency — див. коментар там).
import { apiGetNonEmptyList } from './api';
import type { CompactGridPoint } from '../components/SolarPotentialMap';

// Година, а не доба. Кліматологія PVGIS не змінюється, але СКЛАД сітки
// змінюється щоразу, коли крон pvgis_country_grid додає нові точки й
// перебудовує інтерполяцію — доба затримки означала, що адмін бачить
// "зібрано 100%", а відвідувач добу бачить стару (або порожню) карту.
const SOLAR_GRID_REVALIDATE_SECONDS = 3600;

export async function loadSolarGridPoints(): Promise<CompactGridPoint[]> {
  try {
    return await apiGetNonEmptyList<CompactGridPoint>('/solar-map/grid', SOLAR_GRID_REVALIDATE_SECONDS);
  } catch (err) {
    // Раніше тут стояв мовчазний `.catch(() => [])`, і три різні стани —
    // "сітка ще не порахована", "API недоступний", "мережа впала" —
    // зливались в одне повідомлення "зверніться до адміністратора".
    // Адміністратор при цьому не мав ЖОДНОГО способу дізнатись, до чого
    // саме звертатись. Порожній масив лишається (сторінка не повинна
    // падати через карту), але причина тепер потрапляє в логи функції.
    console.error('[solar-grid] не вдалось завантажити /solar-map/grid:', err);
    return [];
  }
}
