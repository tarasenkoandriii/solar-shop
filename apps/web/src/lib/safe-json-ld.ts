// Найдено при полном аудите проекта (AUDIT-FULL.md): наивный
// `JSON.stringify(obj)`, вставленный в `<script>` через
// `dangerouslySetInnerHTML`, уязвим к преждевременному закрытию тега —
// если любая строка внутри объекта (например, название товара) содержит
// буквально `</script>`, браузер закроет script-тег раньше времени и
// весь остаток строки отрендерится как обычный HTML — классическая
// JSON-in-script-tag XSS. Источник строк здесь — каталог (админ или
// Grok-сгенерированные описания, ТЗ п.26.3) — не прямой пользовательский
// ввод, но оба канала не гарантируют отсутствие `</script>` в тексте, так
// что экранирование нужно как defense-in-depth, не полагаемся на
// "источник доверенный".
export function safeJsonLdStringify(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026');
}
