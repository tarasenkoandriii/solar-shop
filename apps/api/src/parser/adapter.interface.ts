// Общий интерфейс адаптера парсера (ТЗ п.13.2) — один адаптер на сайт-
// источник. Новый Vendor подключается написанием нового адаптера,
// реализующего этот интерфейс, без изменений в остальном пайплайне.
export interface RawListing {
  sourceUrl: string;
  sourceSku?: string;
  rawTitle: string;
  rawCategory?: string;
  // За прямим запитом користувача — сирий текст категорії, як сторінка
  // сама його показує (H1/breadcrumb), окремо від rawCategory
  // (внутрішній ключ, який ми свідомо шукаємо). Однакове для всіх
  // товарів з одного виклику fetchCategory() — сторінка категорії одна
  // на всю пагінацію, мітка не змінюється між сторінками.
  siteCategoryLabel?: string;
  rawPrice: number; // как на сайте, обычно UAH
  rawCurrency: string;
  inStock: boolean;
  images: string[];
}

export interface ISourceAdapter {
  /** Уникальный ключ адаптера — должен совпадать с Vendor.name в БД */
  readonly vendorName: string;

  // За прямим запитом користувача — "добавить тайм менеджмент и
  // сделать идемпотентным" (повторний запит — попередня реалізація
  // тайм-боксувала лише МІЖ вендорами, не ВСЕРЕДИНІ одного, реальний
  // прогін на sunshop.com.ua завис довше за весь HTTP-таймаут Vercel,
  // 300с, розділ README). Повний курсор-based резюмовний інтерфейс
  // (пауза/продовження з точної сторінки між ОКРЕМИМИ cron-запусками)
  // — надмірне ускладнення архітектури для цього обсягу задачі.
  // Замість цього: адаптер сам перевіряє дедлайн ВСЕРЕДИНІ свого
  // циклу сторінок/категорій — якщо час вичерпано, перериває обхід і
  // повертає ЧАСТКОВИЙ результат з isComplete:false. ParserService
  // зберігає зібране (ідемпотентно, upsert по sourceUrl — вже наявна
  // логіка) і НЕ позначає вендора lastFullyParsedAt, якщо результат
  // неповний — той самий вендор знову опиниться першим у черзі
  // наступного прогону.
  fetchListings(deadlineAt: number): Promise<{ listings: RawListing[]; isComplete: boolean }>;
}
