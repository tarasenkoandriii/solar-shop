// Реквізити компанії — єдине джерело для всього apps/api (рахунки,
// кошториси, бізнес-плани).
//
// За запитом користувача (27.08.2026) підставлено реальні дані. Доти
// InvoiceService друкував покупцю рядки "Постачальник: ФОП [ПІБ]
// (заповнити перед запуском)" і "IBAN: [IBAN], Банк: [Назва банку]" —
// тобто клієнт отримував документ, за яким фізично неможливо заплатити.
// Це була окрема знахідка аудиту.
//
// УВАГА: у apps/web є свій такий самий файл (src/lib/company.ts) —
// застосунки не мають спільного пакета для констант, а заводити його
// заради п'яти рядків надлишково. Змінюєш тут — зміни і там.
//
// Окремо: це ТОВ, а не ФОП. Стара заглушка казала "ФОП Тарасенко Андрій
// Євгенійович" — інша організаційна форма, і в рахунку це не косметика.
export const COMPANY = {
  legalName: 'ТОВ «ХЕЙСЛОР ФАСТ»',
  edrpou: '44697367',
  address: 'Україна, 03110, м. Київ, пров. Караїмський, буд. 12',
  phone: '+380 75 365 75 86',
  email: 'heyslor@ukr.net',

  // Банківські реквізити користувач свідомо не надав ("остальные
  // реквизиты не нужны"). Порожній рядок, а НЕ вигаданий номер і не
  // плейсхолдер: рядок просто не друкується. Щойно з'явиться IBAN —
  // вписати сюди, і він сам проступить у рахунку й на сторінці оплати.
  iban: '',
  bank: '',
} as const;

// Рядки шапки постачальника для PDF. Порожні реквізити відсіюються, щоб
// у документ не потрапляв напівпорожній рядок на кшталт "IBAN: , Банк: ".
export function companyInvoiceLines(): string[] {
  const lines = [
    `Постачальник: ${COMPANY.legalName}`,
    `ЄДРПОУ: ${COMPANY.edrpou}`,
    `Адреса: ${COMPANY.address}`,
    `Тел.: ${COMPANY.phone}   E-mail: ${COMPANY.email}`,
  ];

  if (COMPANY.iban) {
    lines.push(COMPANY.bank ? `IBAN: ${COMPANY.iban}   Банк: ${COMPANY.bank}` : `IBAN: ${COMPANY.iban}`);
  }

  return lines;
}
