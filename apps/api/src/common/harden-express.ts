import type { Express } from 'express';

// АУДИТ 27.08.2026.
//
// Чому це окремий файл, а не два рядки в main.ts: у проєкту ДВА незалежні
// бутстрапи — apps/api/src/main.ts (Docker, локальний запуск) і
// apps/api/api/index.ts (Vercel serverless, тобто реальний прод). Вони вже
// розійшлися одного разу, і будь-яке налаштування, дописане тільки в
// main.ts, на прод фізично не потрапляє. Усе, що має діяти всюди, живе
// тут і викликається з обох точок входу.
//
// Обидва налаштування нижче стосуються одного й того самого: Express за
// замовчуванням довіряє тому, що надіслав клієнт, а ми будуємо на цих
// значеннях рішення про доступ і про ліміти.
export function hardenExpress(app: Express): void {
  // 1. Інʼєкція у фільтр Prisma через рядок запиту.
  //
  // Express розбирає query через qs ("extended"), тому
  //   GET /cart?sessionId[not]=x
  // дає контролеру не рядок, а обʼєкт { not: 'x' }. Глобальний
  // ValidationPipe тут не рятує: для метатипу String transformPrimitive()
  // приводить лише Boolean і Number, решту віддає як є. Обʼєкт-оператор
  // долітав до `where: { sessionId }` — і GET /cart віддавав перший-ліпший
  // чужий гостьовий кошик без жодної авторизації. Той самий прийом у тілі
  // запиту закритий окремо, через DTO (див. MergeGuestSessionDto).
  //
  // 'simple' розбирає рядок запиту модулем querystring: вкладених обʼєктів
  // не буває в принципі. Повторювані ключі
  // (?manufacturerId=a&manufacturerId=b у фільтрі каталогу) далі дають
  // масив — це єдине місце, що залежало від складного розбору, перевірено
  // окремо. Фікс саме тут, а не в кожному контролері: закриває весь клас
  // помилок разом, включно з ендпоінтами, які ще не написані.
  app.set('query parser', 'simple');

  // 2. Довіра до X-Forwarded-For.
  //
  // Дефолт — 0, тобто НЕ довіряти заголовку взагалі: req.ip дорівнює
  // адресі сокета. Це свідомо консервативно. Обхід rate limit підробкою
  // заголовка лікується не тут, а в resolveClientIp() — там же пояснено,
  // чому саме `trust proxy` цю задачу не вирішує (спойлер: проксі ДОПИСУЄ
  // адрес справа, тож 'trust proxy: 1' повертає рівно те значення, яке
  // надіслав клієнт; перевірено запуском).
  //
  // Змінна лишається для випадків, коли req.ip потрібен правильним для
  // логів чи req.protocol — постав TRUSTED_PROXY_HOPS за кількістю
  // ВЛАСНИХ проксі перед застосунком.
  const hops = Number(process.env.TRUSTED_PROXY_HOPS ?? '0');
  app.set('trust proxy', Number.isFinite(hops) && hops >= 0 ? hops : 0);
}
