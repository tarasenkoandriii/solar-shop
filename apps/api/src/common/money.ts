// Аудит 27.08.2026. Ця функція вже жила приватною копією в
// parser.service.ts. Коли знадобилася друга — в OrdersService — стало
// зрозуміло, що копіювати її вдруге не можна: у проєкті вже є історія
// того, як два місця рахують гроші трохи по-різному й розходяться
// непомітно (див. історію з cachedPriceUsd проти cachedCostPriceUsd).
//
// Чому округлення взагалі потрібне: всі грошові колонки — Decimal(10,2),
// але арифметика над ними в коді йде через Number(), тобто через
// плаваючу кому. `1000 * (1 - 90 / 100)` дає 99.99999999999997, а не 100
// (перевірено). Prisma такий хвіст мовчки обріже при записі — і в базі
// опиниться одне число, а в листі покупцю чи в розрахунку прибутку інше.
//
// Це НЕ повноцінне лікування грошей на float — правильне рішення
// довгострокове — рахувати в Decimal або в цілих копійках наскрізь.
// Але явне округлення в точках запису прибирає найпомітніший наслідок
// і коштує один рядок.
export function roundToCents(value: number): number {
  return Math.round(value * 100) / 100;
}
